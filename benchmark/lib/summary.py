#!/usr/bin/env python3
"""
lib/summary.py

Read meta.json from every suite's results/ directory and render SUMMARY.md.

Usage:
  python3 lib/summary.py --benchmark-root . --output SUMMARY.md
"""
from __future__ import annotations
import argparse, json
from datetime import datetime, timezone
from pathlib import Path

SUITES_ORDER = [
    "01_hw_counters",
    "02_cpu_microarch",
    "03_latency",
    "04_throughput",
    "05_interrupt",
    "06_memory_dma",
    "07_queue_scaling",
    "08_offloads",
    "09_flamegraph",
    "10_stress",
    "11_ebpf_xdp",
]

STATUS_ICON = {
    "PASS"     : "✅ PASS",
    "WARN"     : "⚠️ WARN",
    "FAIL"     : "🔴 FAIL",
    "BASELINE" : "🔵 BASELINE",
    "SKIP"     : "⬛ SKIP",
}


def load_env(benchmark_root: Path) -> dict:
    """Try to read env.json from any suite that has results."""
    for suite in SUITES_ORDER:
        p = benchmark_root / suite / "results" / "env.json"
        if p.exists():
            try:
                return json.loads(p.read_text())
            except Exception:
                pass
    return {}


def load_meta(benchmark_root: Path, suite: str) -> dict | None:
    for candidate in [
        benchmark_root / suite / "results" / "meta.json",
        benchmark_root / suite / "meta.json",
    ]:
        if candidate.exists():
            try:
                return json.loads(candidate.read_text())
            except Exception:
                pass
    return None


def render_summary(benchmark_root: Path, output: Path) -> None:
    env      = load_env(benchmark_root)
    ts       = datetime.now(timezone.utc).strftime("%Y-%m-%d %H:%M UTC")
    run_id   = env.get("timestamp", ts)[:19].replace("T", " ")

    rows     = []
    statuses = []

    for suite in SUITES_ORDER:
        meta = load_meta(benchmark_root, suite)
        if meta:
            status     = meta.get("status", "UNKNOWN")
            key_metric = meta.get("key_metric", "—")
            vs_base    = meta.get("vs_baseline", "—")
            ts_str     = meta.get("timestamp", "")[:16].replace("T", " ")
        else:
            status     = "SKIP"
            key_metric = "not run"
            vs_base    = "—"
            ts_str     = "—"

        statuses.append(status)
        icon = STATUS_ICON.get(status, status)
        report_link = f"[REPORT.md]({suite}/REPORT.md)"
        rows.append([f"`{suite}`", icon, key_metric, vs_base, ts_str, report_link])

    # Overall status
    if any(s == "FAIL" for s in statuses):
        overall = "🔴 FAIL"
    elif any(s == "WARN" for s in statuses):
        overall = "⚠️ WARN"
    elif all(s in ("PASS", "BASELINE") for s in statuses if s != "SKIP"):
        overall = "✅ PASS"
    else:
        overall = "⬛ PARTIAL"

    n_pass = sum(1 for s in statuses if s in ("PASS", "BASELINE"))
    n_warn = sum(1 for s in statuses if s == "WARN")
    n_fail = sum(1 for s in statuses if s == "FAIL")
    n_skip = sum(1 for s in statuses if s == "SKIP")

    # Header
    lines = [
        "# Mellanox Driver Benchmark — Summary",
        "",
        f"| | |",
        f"|:---|:---|",
        f"| **Overall status** | {overall} |",
        f"| **Run** | {ts} |",
    ]
    if env:
        lines += [
            f"| **Driver** | `{env.get('driver_version', '?')}` |",
            f"| **Kernel** | `{env.get('kernel', '?')}` |",
            f"| **FW** | `{env.get('fw_version', '?')}` |",
            f"| **NIC** | `{env.get('nic_pci', '?')}` @ `{env.get('link_speed', '?')}` |",
        ]
    lines += [
        f"| **Results** | ✅ {n_pass} PASS · ⚠️ {n_warn} WARN · "
        f"🔴 {n_fail} FAIL · ⬛ {n_skip} SKIP |",
        "",
        "---",
        "",
        "## Suite Results",
        "",
    ]

    # Table header
    sep    = "|:---|:---|:---|:---|:---|:---|"
    header = "| **Suite** | **Status** | **Key metric** | **vs baseline** | **Run at** | **Report** |"
    lines += [header, sep]
    for row in rows:
        lines.append("|" + "|".join(f" {c} " for c in row) + "|")

    lines += [
        "",
        "---",
        "",
        "## Quick Reference — Key Thresholds",
        "",
        "| Metric | Warn | Regression |",
        "|:---|:---|:---|",
        "| TCP single-stream throughput | −2% | −5% |",
        "| p99 latency (no-load 64B) | +5% | +15% |",
        "| Cache miss rate | +5% | +15% |",
        "| IPC (instructions/cycle) | −5% | −10% |",
        "| NUMA penalty | >3% | >10% |",
        "| Coalescing optimal p99 | +5% | +15% |",
        "| Stress run drops | any | >1 |",
        "| Link flap avg recovery | +10ms | +30ms |",
        "",
        "---",
        "",
        f"_Generated by `lib/summary.py` · {ts}_",
    ]

    output.parent.mkdir(parents=True, exist_ok=True)
    output.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"[summary] Written → {output}")
    print(f"[summary] {overall}  "
          f"pass={n_pass} warn={n_warn} fail={n_fail} skip={n_skip}")


def main() -> None:
    ap = argparse.ArgumentParser()
    ap.add_argument("--benchmark-root", default=".", help="Root of the benchmark/ directory")
    ap.add_argument("--output",         default="SUMMARY.md")
    args = ap.parse_args()
    render_summary(Path(args.benchmark_root), Path(args.output))


if __name__ == "__main__":
    main()
